/** criterion(lang, 'DFMEA', 'S', 7) → text (falls back to English). overrides: {'DFMEA.S': {7: 'custom'}} */
export function criterion(lang, type, letter, value, overrides) {
  const key = `${type === 'MSR' ? 'MSR' : type}.${letter}`;
  const ov = overrides && overrides[key] && overrides[key][value];
  if (ov) return ov;
  const tab = (CRITERIA[lang] || CRITERIA.en)[key] || CRITERIA.en[key];
  return tab ? tab[10 - value] : '';
}
export function table(lang, type, letter, overrides) { const out = []; for (let v = 10; v >= 1; v--) out.push({ value: v, text: criterion(lang, type, letter, v, overrides) }); return out; }
